"""Builds datasets/synthetic: CV files, their ground truth, vacancies and the fairness variants."""

from __future__ import annotations

import json
import random
from dataclasses import replace
from datetime import date
from pathlib import Path

from clearhire.synth.archetypes import ARCHETYPES
from clearhire.synth.generate import (
    REFERENCE_DATE,
    TruthCandidate,
    TruthVacancy,
    make_candidates,
    make_vacancies,
    person_name,
)
from clearhire.synth.render import TEMPLATES, write_cv

FORMATS = (("pdf", 60), ("docx", 28), ("scan", 12))
EXTENSIONS = {"pdf": "pdf", "docx": "docx", "scan": "pdf"}
FAIRNESS_PER_LANGUAGE = {"ru": 36, "en": 18}

README = """# Synthetic CV dataset

Generated by `clearhire synth` (seed {seed}, reference date {today}). Every person, company and contact
here is fictional: names come from common-name lists, phone numbers use the unassigned "+7 000" range,
e-mail addresses use example.com, and Telegram handles are `@cand_<id>`. Released under CC0.

| File | What it holds |
| --- | --- |
| `cvs/` | {count} CVs: {formats} |
| `candidates.jsonl` | The record each CV was written from: roles with dates and the skills each names, listed skills, languages and levels, degree |
| `vacancies.jsonl` | {vacancies} vacancies (13 roles × junior, middle, senior), with the structured requirements their text was written from |
| `fairness/` | {variants} variants of {fair} CVs: the other gender (in Russian also the verb endings), a name of another origin, an older birth date |
| `fairness.jsonl` | What each variant changed |

CV layouts: Russian classic, hh.ru-style (dates first, gender and age in the header) and compact;
English classic, compact (one line per role, sometimes years only) and a two-column sidebar.
"""


def build_dataset(out: Path, count: int = 312, seed: int = 42) -> dict[str, int]:
    rng = random.Random(seed + 7)
    (out / "cvs").mkdir(parents=True, exist_ok=True)
    (out / "fairness").mkdir(parents=True, exist_ok=True)
    candidates = make_candidates(count, seed)
    formats_written = {"pdf": 0, "docx": 0, "scan": 0}
    for candidate in candidates:
        candidate.template = rng.choice(TEMPLATES[candidate.language])
        file_format = rng.choices([f for f, _ in FORMATS], weights=[w for _, w in FORMATS])[0]
        if candidate.template == "sidebar" and file_format == "docx":
            file_format = "pdf"  # a two-column Word table reads back as one interleaved line per row
        candidate.file_format = file_format
        candidate.file = f"cvs/{candidate.id}.{EXTENSIONS[file_format]}"
        (out / candidate.file).write_bytes(write_cv(candidate, candidate.template, file_format))
        formats_written[file_format] += 1
    with (out / "candidates.jsonl").open("w", encoding="utf-8", newline="\n") as handle:
        for candidate in candidates:
            handle.write(json.dumps(candidate.to_dict(), ensure_ascii=False) + "\n")

    vacancies = make_vacancies(seed)
    with (out / "vacancies.jsonl").open("w", encoding="utf-8", newline="\n") as handle:
        for vacancy in vacancies:
            handle.write(json.dumps(vacancy.to_dict(), ensure_ascii=False) + "\n")

    variants = write_fairness(out, candidates, seed)
    (out / "README.md").write_text(
        README.format(
            seed=seed, today=REFERENCE_DATE.isoformat(), count=len(candidates), vacancies=len(vacancies),
            formats=", ".join(f"{n} {k.upper() if k != 'scan' else 'scanned PDFs (image only, need OCR)'}"
                              for k, n in formats_written.items()),
            variants=variants, fair=sum(FAIRNESS_PER_LANGUAGE.values()),
        ),
        encoding="utf-8", newline="\n",
    )  # fmt: skip
    return {
        "candidates": len(candidates),
        "vacancies": len(vacancies),
        "fairness_variants": variants,
        **formats_written,
    }


def write_fairness(out: Path, candidates: list[TruthCandidate], seed: int) -> int:
    """Re-render chosen CVs with only personal details changed. Scans are re-rendered as plain PDFs so
    OCR noise cannot be mistaken for a fairness effect."""
    rng = random.Random(seed + 11)
    rows: list[dict[str, str]] = []
    for language, quota in FAIRNESS_PER_LANGUAGE.items():
        pool = [c for c in candidates if c.language == language]
        for candidate in rng.sample(pool, min(quota, len(pool))):
            file_format = "pdf" if candidate.file_format == "scan" else candidate.file_format
            other_gender = "m" if candidate.gender == "f" else "f"
            other_origin = {"ru": "world-3", "world-3": "ru", "en": "world-0"}.get(candidate.origin, "en")
            variant_rng = random.Random(f"{seed}-{candidate.id}")
            versions: dict[str, TruthCandidate] = {"original": candidate}
            first, last = person_name(candidate.origin, other_gender, candidate.language, variant_rng)
            versions["gender"] = replace(candidate, gender=other_gender, first_name=first, last_name=last)
            first, last = person_name(other_origin, candidate.gender, candidate.language, variant_rng)
            versions["origin"] = replace(candidate, origin=other_origin, first_name=first, last_name=last)
            older = candidate.birth
            versions["age"] = replace(candidate, birth=date(older.year - 15, older.month, older.day))
            for variant, version in versions.items():
                name = f"fairness/{candidate.id}--{variant}.{EXTENSIONS[file_format]}"
                data = write_cv(version, candidate.template, file_format, gender=version.gender)
                (out / name).write_bytes(data)
                rows.append({"id": candidate.id, "variant": variant, "file": name, "gender": version.gender,
                             "name": version.full_name, "birth": version.birth.isoformat()})  # fmt: skip
    with (out / "fairness.jsonl").open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    return len(rows)


def load_dataset(root: Path) -> tuple[list[TruthCandidate], list[TruthVacancy]]:
    candidates = [TruthCandidate.from_dict(json.loads(line))
                  for line in (root / "candidates.jsonl").read_text(encoding="utf-8").splitlines() if line]  # fmt: skip
    vacancies = [TruthVacancy.from_dict(json.loads(line))
                 for line in (root / "vacancies.jsonl").read_text(encoding="utf-8").splitlines() if line]  # fmt: skip
    return candidates, vacancies


__all__ = ["ARCHETYPES", "build_dataset", "load_dataset"]
